"""`make eval` / `make eval-quick`: run the evaluation suite, regenerate the numbers and the
report. Exits non-zero if any step fails (so `make check` can never pass on stale numbers).

    python evals/run_all.py [--quick]
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "evals" / "results"
LIMITATIONS = ROOT / "docs" / "03-EVAL-AND-DEMO.md"


def _rows(path: Path) -> list[dict]:
    if not path.exists():
        return []
    lines = [line for line in path.read_text(encoding="utf-8").splitlines()
             if line and not line.startswith("#")]
    return list(csv.DictReader(io.StringIO("\n".join(lines))))


def _table(rows: list[dict], columns: list[str]) -> str:
    if not rows:
        return "_no rows_\n"
    head = "| " + " | ".join(columns) + " |"
    sep = "|" + "|".join("---" for _ in columns) + "|"
    body = []
    for row in rows:
        cells = []
        for col in columns:
            value = row.get(col, "")
            cells.append("" if value is None else str(value))
        body.append("| " + " | ".join(cells) + " |")
    return "\n".join([head, sep, *body]) + "\n"


def _limitations() -> str:
    if not LIMITATIONS.exists():
        return ""
    text = LIMITATIONS.read_text(encoding="utf-8")
    start = text.find("## 7. Honest limitations")
    if start < 0:
        return ""
    end = text.find("## 8.", start)
    return text[start:end if end > 0 else None].strip()


def build_report(info: dict, numbers: dict, results: Path | None = None) -> str:
    results = results or RESULTS
    semantics = _rows(results / "e1_semantics.csv")
    samples = _rows(results / "e1_samples.csv")
    generated = datetime.now(UTC).astimezone().strftime("%Y-%m-%d %H:%M %Z")
    parts = [
        "# EVAL REPORT (generated by `make eval` - do not edit by hand)",
        "",
        f"Generated: {generated} | commit: {info.get('commit_sha', 'unknown')}",
        f"Machine: {info.get('os', '?')} | CPU {info.get('cpu', '?')} ({info.get('cpu_count', '?')} cores)"
        f" | RAM {info.get('ram_gb', '?')} GB | python {info.get('python', '?')}"
        f" | FalkorDB module {info.get('falkor_module_version', '?')}",
        "",
        "## E1 - contamination semantics ( Pedigree vs B0/B1/B2/B4/B5 )",
        "",
        "One generated lineage DAG per seed with one revoked source; ground truth from the",
        "**independent** oracle `evals/oracle.py`; Pedigree's numbers come from the engine's real",
        "`compute_final`, cross-checked against a real FalkorDB revoke in",
        "`tests/evals/test_oracle_agreement.py`. Baselines B0-B5 are emulations of the semantics",
        "described in docs/03 section 2, not the vendors' products.",
        "`preserved_correct` is sensitivity of the explicit preserved status against the",
        "oracle-supported set. A baseline zero does not prove all supported items were",
        "discarded: untouched items need not have that status. Retention and preservation",
        "precision require separate metrics and are not established by this score.",
        "",
    ]
    if numbers:
        parts.append("### Headline numbers (pooled ratios; stratified seed-cluster bootstrap 95% CI)")
        parts.append("")
        keys = sorted(k for k in numbers if k.startswith("e1_") and isinstance(numbers[k], dict))
        parts.append(_table(
            [{"key": k, "value": numbers[k]["value"], "ci95": str(numbers[k].get("ci95")),
              "n_clusters": numbers[k].get("n_clusters"), "n_items": numbers[k].get("n_items")} for k in keys],
            ["key", "value", "ci95", "n_clusters", "n_items"]))
    parts.append("Intervals are conditional on the finite generator grid. A degenerate empirical bootstrap does not establish certainty. Undefined denominators are null; n counts valid seed clusters, with item counts recorded separately in JSON.")
    parts.append("### Per cell (mean +- bootstrap 95% CI over seeds)")
    parts.append("")
    cols = ["cell", "system", "recall", "over_invalidation", "preserved_correct",
            "action_recall", "irreversible_recall", "n_seeds"]
    cols += [f"{metric}_{suffix}" for metric in ("recall", "over_invalidation", "preserved_correct", "action_recall", "irreversible_recall") for suffix in ("lo", "hi", "n_seeds")]
    parts.append(_table(semantics, cols))
    parts.append("")
    parts.append("## E2 - capture fidelity (edge drops and conservative read windows)")
    parts.append("")
    parts.append("Model, stated plainly: (a) *precise capture with missing edges* drops each")
    parts.append("DERIVED_FROM edge independently with probability d (one draw stream per seed, so a")
    parts.append("higher rate always drops a superset of the edges); (b) *conservative read-window")
    parts.append("capture* gives every write its true parents plus up to K carried-over reads from the")
    parts.append("same modelled session (docs/01 section 7.3 \"last K READ targets\"; 5 actions per")
    parts.append("session). E2 is a model of capture")
    parts.append("error, not a measurement of real runtime coverage. E6 is NOT MEASURED: one genuine installed OpenCode read-hook shape is verified, but there is no labeled coverage or benign-friction corpus.")
    parts.append("")
    e2 = _rows(results / "e2_capture.csv")
    parts.append(_table(e2, ["kind", "param", "recall", "leakage", "over_flag_ratio",
                             "extra_actions", "n_g", "n_actions"] +
                        [f"{metric}_{suffix}" for metric in ("recall", "leakage", "over_flag_ratio", "extra_actions") for suffix in ("lo", "hi", "n_seeds")]))
    parts.append("")
    parts.append("## E4 - latency (real FalkorDB, real engine calls)")
    parts.append("")
    parts.append("One throwaway graph per size, built through the engine, then the real engine")
    parts.append("timed over rounds (the real revoke uses a different root per round, because a")
    parts.append("second revoke of the same root is idempotent by design). `build_ms` is the")
    parts.append("per-node write path through the engine, not a bulk loader - reported as-is.")
    parts.append("")
    e4 = _rows(results / "e4_latency.csv")
    parts.append(_table(e4, ["nodes", "build_ms", "revoke_dry_p50_ms", "revoke_real_p50_ms",
                             "revoke_real_p95_ms", "blame_p50_ms", "impact_p50_ms", "gate_p50_ms"]))
    parts.append("")
    parts.append("## E3 - scenario replay through the HTTP API")
    parts.append("")
    parts.append("`evals/run_e3.py` (also `tests/evals/test_e3_scenarios.py`) POSTs every")
    parts.append("authored `demo/scenarios/*.json` node through `/v1/events`, attests the")
    parts.append("corroborations with the operator credential, revokes the root through")
    parts.append("`/v1/revoke` and asserts the fixture's expected statuses plus gate verdicts: the")
    parts.append("high-risk push built on the revoked branch is never `allow`, and a private tag")
    parts.append("reaching a public audience is `block` with its path.")
    parts.append("Trusted human/scanner support attestation requires the operator credential under the source-identity/trust ADR-008; arbitrary MCP agent claims do not grant that authority.")
    parts.append("")

    parts.append("## E5 - scoped isolation and concurrency verification")
    parts.append("")
    parts.append("Current local verification covers three integration tests in `tests/integration/test_isolation_concurrency.py`: the API isolation matrix, threaded tenant stress with invariant checks, and revoke-during-ingest consistency. These tests do not prove absence of all isolation or race defects.")
    parts.append("The optional database ACL mechanism test in `tests/security/test_acl_mechanism.py` is skipped without its deployment secret. The service still uses a shared administrative database connection; wiring per-tenant database credentials into the running service remains open. A separately configured ACL mechanism is not proof of that service boundary.")
    parts.append("")
    parts.append("## E6 / E3b - NOT MEASURED")
    parts.append("")
    parts.append("The 2026-10-16 free-only installed OpenCode recheck captured one genuine read-tool before/after hook shape. Its final response timed out; this is payload-shape evidence, not a labeled coverage or benign-friction corpus. The current S1/S8 demo is synthetic. The recorded-session experiment and live-agent video remain planned work.")
    parts.append("")

    parts.append("## E4b - FalkorDB vs SQLite traversal (honest answer)")
    parts.append("")
    parts.append("Same closure/ancestor queries in FalkorDB (`algo.BFS`, over the socket) and in")
    parts.append("stdlib `sqlite3` (`WITH RECURSIVE`, in-process) on the same generated DAG, with")
    parts.append("the descendant and ancestor ID sets asserted equal. Scope: the traversal primitives only - not the")
    parts.append("revoke pipeline. The measured traversal timings are reported below; conclusions apply")
    parts.append("only to these rows and this host (the graph query pays a round-trip). What FalkorDB")
    parts.append("provides this implementation is one graph per tenant, `GRAPH.COPY` for an isolated what-if, and")
    parts.append("database ACLs. SQLite can also support logical isolation; this benchmark does not compare those architectures.")
    parts.append("")
    e4b = _rows(results / "e4b_falkor_vs_sqlite.csv")
    parts.append(_table(e4b, ["nodes", "edges", "closure_nodes", "closure_sqlite_ms",
                              "closure_falkor_ms", "ancestors_sqlite_ms", "ancestors_falkor_ms"]))
    parts.append("")
    artifact_dir = results.relative_to(ROOT) if results.is_relative_to(ROOT) else results
    parts.append(f"`{(artifact_dir / 'e1_samples.csv').as_posix()}` ({len(samples)} rows), "
                 f"`{(artifact_dir / 'e1_b0_theta_sweep.csv').as_posix()}`.")
    parts.append("")
    parts.append("## Limitations (docs/03 section 7, verbatim)")
    parts.append("")
    parts.append(_limitations() or "_not found_")
    parts.append("")
    parts.append("## How to reproduce")
    parts.append("")
    parts.append("```bash\nmake eval          # full grid (N>=30 seeds per cell)\n"
                 "make eval-quick    # one cell, 2 seeds\n```")
    return "\n".join(parts)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    args = ap.parse_args(argv)

    results = RESULTS / "quick" if args.quick else RESULTS
    results.mkdir(parents=True, exist_ok=True)
    runner_args = (["--quick"] if args.quick else []) + ["--out", str(results)]
    sys.path.insert(0, str(ROOT))
    from evals import machineinfo  # noqa: PLC0415
    from evals.run_e1 import main as run_e1  # noqa: PLC0415

    print("[eval] E1 contamination semantics ...")
    rc = run_e1(runner_args)
    if rc != 0:
        print("[eval] E1 failed", file=sys.stderr)
        return rc

    print("[eval] E2 capture fidelity ...")
    from evals.run_e2 import main as run_e2  # noqa: PLC0415
    rc = run_e2(runner_args)
    if rc != 0:
        print("[eval] E2 failed", file=sys.stderr)
        return rc

    print("[eval] E4 latency (real engine, sizes capped by this host) ...")
    from evals.run_e4 import main as run_e4  # noqa: PLC0415
    rc = run_e4(runner_args)
    if rc != 0:
        print("[eval] E4 failed", file=sys.stderr)
        return rc

    print("[eval] E3 scenario replay through the HTTP API ...")
    from evals.run_e3 import main as run_e3  # noqa: PLC0415
    rc = run_e3()
    if rc != 0:
        print("[eval] E3 failed", file=sys.stderr)
        return rc

    print("[eval] E4b FalkorDB vs SQLite traversal ...")
    from evals.run_e4b_sqlite import main as run_e4b  # noqa: PLC0415
    rc = run_e4b(runner_args)
    if rc != 0:
        print("[eval] E4b failed", file=sys.stderr)
        return rc

    print("[eval] merging per-experiment numbers ...")
    numbers_path = results / "numbers.json"
    numbers = json.loads(numbers_path.read_text(encoding="utf-8")) if numbers_path.exists() else {}
    from evals.static_numbers import STATIC_NUMBERS  # noqa: PLC0415

    # Static facts are never overwritten by a run; a --quick run writes its own file so it can
    # never replace the published block in docs/NUMBERS.md (that would break `make check`).
    target = results / "numbers.json"
    for key, entry in STATIC_NUMBERS.items():
        numbers.setdefault(key, entry)
    for extra in sorted(results.glob("numbers_*.json")):
        if extra.name in ("numbers.json", "numbers_quick.json"):
            continue
        numbers.update(json.loads(extra.read_text(encoding="utf-8")))
    target.write_text(json.dumps(numbers, indent=2), encoding="utf-8")

    if args.quick:
        (results / "REPORT.md").write_text(build_report(machineinfo.collect(), numbers, results), encoding="utf-8")
        print(f"[eval] quick run: artifacts written to {results}; "
              "docs/NUMBERS.md and evals/REPORT.md unchanged (run `make eval` to publish)")
        return 0

    print("[eval] regenerating docs/NUMBERS.md ...")
    rc = subprocess.call([sys.executable, str(ROOT / "scripts" / "extract_numbers.py")], cwd=ROOT)
    if rc != 0:
        print("[eval] extract_numbers failed", file=sys.stderr)
        return rc

    rc = subprocess.call([sys.executable, str(ROOT / "scripts" / "check_numbers.py")], cwd=ROOT)
    if rc != 0:
        print("[eval] check_numbers failed", file=sys.stderr)
        return rc

    info = machineinfo.collect()
    report = build_report(info, numbers)
    (ROOT / "evals" / "REPORT.md").write_text(report, encoding="utf-8")
    print("[eval] wrote evals/REPORT.md and docs/NUMBERS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
